const dicts: Record<Lang, Dict> = { en, hi };

export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const s = dicts[lang][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function fmtDist(lang: Lang, m: number): string {
  if (m < 950) return t(lang, "m", { v: Math.round(m / 50) * 50 });
  return t(lang, "km", { v: m < 9500 ? (m / 1000).toFixed(1) : Math.round(m / 1000) });
}

export function fmtDuration(lang: Lang, s: number): string {
  const mins = Math.round(s / 60);
  if (mins < 60) return t(lang, "min", { v: mins });
  return t(lang, "hmin", { h: Math.floor(mins / 60), m: mins % 60 });
}

